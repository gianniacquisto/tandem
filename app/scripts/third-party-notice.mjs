import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Generate `THIRD-PARTY.md` from the production dependency closure.
 *
 * The retired editor bundle carried the only licence record of the packages
 * that shipped inside it (`Editor/build.mjs`'s generated `LICENSES.md`). UI-22
 * moved mermaid and KaTeX into the renderer's own graph, so the record moves
 * with them: every package in `package-lock.json` that is not a dev package,
 * its npm-declared licence, and its own verbatim licence text.
 *
 * The allowed set is the bundle's, with its SPDX-expression handling: GPL and
 * AGPL never ship, and an expression is allowed when every alternative it
 * names is. `khroma` is the one override the bundle also carried: its
 * package.json omits the field and its shipped license file is MIT.
 *
 * Deterministic by construction: package order, version order and the licence
 * files' own bytes, all sorted. `node scripts/third-party-notice.mjs` writes
 * the file; `--check` regenerates in memory and fails when the committed copy
 * differs. app.yml runs the writer and diffs the working tree.
 */
const appRoot = fileURLToPath(new URL('..', import.meta.url))
const lockPath = join(appRoot, 'package-lock.json')
const noticePath = join(appRoot, 'THIRD-PARTY.md')

const ALLOWED_LICENSES = new Set([
  'MIT',
  'ISC',
  'MPL-2.0',
  'APACHE-2.0',
  'EPL-2.0',
  'BSD-2-CLAUSE',
  'BSD-3-CLAUSE',
  '0BSD',
  'UNLICENSE',
])

const LICENSE_OVERRIDES = new Map([['khroma', 'MIT']])

function isAllowedLicense(declared) {
  if (typeof declared !== 'string' || declared.trim() === '') return false
  return declared
    .trim()
    .replace(/^\((.*)\)$/, '$1')
    .split(/\s+(?:OR|AND)\s+/i)
    .map((part) => part.trim().toUpperCase())
    .every((part) => ALLOWED_LICENSES.has(part))
}

function licenseText(pkgDir, name) {
  let entries
  try {
    entries = readdirSync(pkgDir).sort()
  } catch {
    throw new Error(`${name}: cannot read ${pkgDir}`)
  }
  for (const entry of entries) {
    if (!/^licen[cs]e(\.|$)/i.test(entry)) continue
    const file = join(pkgDir, entry)
    if (statSync(file).isFile()) return readFileSync(file, 'utf8').replace(/\s+$/, '')
  }
  throw new Error(`${name}: no license file under ${pkgDir}`)
}

function compare(a, b) {
  if (a.name !== b.name) return a.name < b.name ? -1 : 1
  if (a.version === b.version) return 0
  return a.version < b.version ? -1 : 1
}

const lock = JSON.parse(readFileSync(lockPath, 'utf8'))
const packages = []
for (const [path, entry] of Object.entries(lock.packages ?? {})) {
  if (path === '' || entry.dev === true || entry.link === true) continue
  const pkgDir = join(appRoot, path === '' ? '.' : path)
  const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))
  const name = typeof pkg.name === 'string' ? pkg.name : path
  const version = pkg.version ?? entry.version ?? ''
  const declared =
    (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type) ??
    entry.license ??
    LICENSE_OVERRIDES.get(name)
  if (!isAllowedLicense(declared)) {
    throw new Error(`license not allowed in the app: ${name} (${declared ?? 'none declared'})`)
  }
  packages.push({ name, version, license: declared, pkgDir })
}
packages.sort(compare)

const rows = packages
  .map((pkg) => `| \`${pkg.name}\` | ${pkg.version} | ${pkg.license} |`)
  .join('\n')
const blocks = packages
  .map((pkg) => `### \`${pkg.name}\` (${pkg.version})\n\n${licenseText(pkg.pkgDir, pkg.name)}`)
  .join('\n\n')

const notice = `# Third-party licenses: Tandem

Generated by \`scripts/third-party-notice.mjs\` from \`package-lock.json\`. Do
not edit by hand. The committed app carries the production dependency closure
of \`package.json\` (development packages excluded): React, KaTeX, mermaid and
their transitive packages, including the licence texts below, verbatim from
each package's own file.

Every package is under a permissive licence (MIT, ISC, MPL-2.0, Apache-2.0,
EPL-2.0 or BSD); GPL and AGPL never ship, and the generator fails if a package
outside that set ever joins the graph.

| package | version | license |
| --- | --- | --- |
${rows}

## License texts

${blocks}
`

if (process.argv.includes('--check')) {
  const committed = (() => {
    try {
      return readFileSync(noticePath, 'utf8')
    } catch {
      return null
    }
  })()
  if (committed !== notice) {
    console.error('THIRD-PARTY.md is stale: run node scripts/third-party-notice.mjs')
    process.exit(1)
  }
  console.log(`THIRD-PARTY.md is current (${packages.length} production packages)`)
} else {
  writeFileSync(noticePath, notice)
  console.log(`wrote ${noticePath} (${packages.length} production packages)`)
}
